/* La do...while instrucción se repite hasta que una condición específica se evalúe como falsa. 
**El bloque de código se ejecuta una vez obligatoriamente.
**Después se evalúa la condición.
**Si la condición es true, el bloque se vuelve a ejecutar.
**Si la condición es false, el bucle termina.
*/

do
  statement
while (condition);