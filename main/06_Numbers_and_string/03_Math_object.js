/* 
El objeto integrado Math tiene propiedades y métodos para constantes y funciones matemáticas. Por ejemplo, 
la propiedad Math del objeto PI tiene el valor de pi (3.141…), que se usaría en una aplicación como
*/

console.log(Math.PI)
console.log(Math.sin(1.56))
console.log(Math.floor(4.9)); // 4 redondea hacia abajo
console.log(Math.ceil(4.1)); // 5 redondea hacia arriba
console.log(Math.min(5, 1, 9)); // 1
console.log(Math.max(5, 1, 9)); // 9
console.log(Math.random()); // número entre 0 y 1